func GetSubjectPrompt(subject entity.Subject) string {
	switch subject {
	case entity.SubjectMath:
		return MathPrompt
	case entity.SubjectEnglish:
		return EnglishPrompt
	case entity.SubjectPhysics:
		return PhysicsPrompt
	case entity.SubjectChemistry:
		return ChemistryPrompt
	case entity.SubjectHistory:
		return HistoryPrompt
	case entity.SubjectBiology:
		return BiologyPrompt
	case entity.SubjectGeography:
		return GeographyPrompt
	default:
		return TutorSystemPrompt
	}
}
